    private void IniciaLizarWebCam(){
        try{
            ODB_Parameter._dimensaoDefault = WebcamResolution.VGA.getSize();
            ODB_Parameter._Webcam = Webcam.getDefault();
            ODB_Parameter._Webcam.setViewSize(ODB_Parameter._dimensaoDefault);

            for(Dimension dimensao : ODB_Parameter._Webcam.getViewSizes()){
                System.out.println("Largura: " + dimensao.getWidth() + "Largura: " + dimensao.getHeight());
            }
        }catch(WebcamException ex){
            JOptionPane.showMessageDialog(null, ex.getMessage(), "AVISO", JOptionPane.PLAIN_MESSAGE);
        }
    }
    
    private void Inicializa_Captura(){
        new Thread(){
            
            @Override
            public void run(){
                while(true){
                    try{
                        Image _foto = ODB_Parameter._Webcam.getImage();
                        ImageIcon _iconn = new ImageIcon(_foto);
                        _iconn.setImage(_iconn.getImage().getScaledInstance(LbFoto.getWidth(), LbFoto.getHeight(), 100));
                        LbFoto.setIcon(_iconn);
                        Thread.sleep(50);
                        
                    }catch(Exception ex){
                        JOptionPane.showMessageDialog(null, ex.getMessage(), "AVISO", JOptionPane.PLAIN_MESSAGE);
                    }
                }
            }
        }.start();
    }
    private void BtFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtFotoActionPerformed
        // TODO add your handling code here:
        try
        {
            if(RdImportar.isSelected()){
                JFileChooser chooser = new JFileChooser();
                chooser.showOpenDialog(null);

                File file = chooser.getSelectedFile();
                ODB_Parameter.CaminhoFoto = file.getAbsolutePath();

                ImageIcon icone1 = new ImageIcon(ODB_Parameter.CaminhoFoto);
                Image img = icone1.getImage().getScaledInstance(LbFoto.getWidth(), LbFoto.getHeight(), Image.SCALE_DEFAULT);
                LbFoto.setIcon(new ImageIcon(img));
            
            }else if (RdWebCam.isSelected()){
                
                new Thread(){
                    public void run(){
                        LbFoto.setText("Inicializando leitura...");
                        
                        ODB_Parameter._Webcam.open();
                        
                        LbFoto.setText("");
                        
                        Inicializa_Captura();
                    }
                    
                }.start();
                
            }else{
                throw new Exception("FAVOR SELECIONE UMA DAS OPÇÕES AO LADO");
            }
        }catch(Exception ex){
            JOptionPane.showMessageDialog(null, ex.getMessage(), "AVISO", JOptionPane.PLAIN_MESSAGE);
        }

    }//GEN-LAST:event_BtFotoActionPerformed

