    private void TxCPFKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TxCPFKeyPressed
        try{
            if(evt.getKeyCode() == KeyEvent.VK_ENTER){
                if(TxCPF.getText().isEmpty()){
                    
                    throw new Exception("CAMPO CPF/CNPJ NÃO PODE SER NULO, FAVOR VERIFIQUE");
                    
                }else{
                    
                    ODB_Validador valida = new ODB_Validador();
                    
                    if(TxCPF.getText().trim().length() == 11)
                    {
                        Boolean RetornoCPF = valida.isCPF(TxCPF.getText());

                        if(RetornoCPF.equals(false)){

                            throw new Exception("CPF INVÁLIDO, FAVOR VERIFIQUE");
                        }
                        else{

                            TxRG.requestFocus();
                        }
                    }else if (TxCPF.getText().trim().length() == 14){
                        
                        Boolean RetornoCNPJ = valida.isCNPJ(TxCPF.getText());
                        
                        if(RetornoCNPJ.equals(false)){
                            throw new Exception("CNPJ INVÁLIDO, FAVOR VERIFIQUE");
                        }else{
                            TxRG.requestFocus();
                        }
                    }else{
                        throw new Exception("CNPJ OU CNPJ INVÁLIDO");
                    }
                }
            }
        }catch(Exception ex){
            JOptionPane.showMessageDialog(null, ex.getMessage(),"ERRO",JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_TxCPFKeyPressed

