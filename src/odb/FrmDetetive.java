    private void BtSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtSalvarActionPerformed
        try{
            
                Date data = new Date();
                Calendar Nascimento = Calendar.getInstance();
                SimpleDateFormat format = new SimpleDateFormat("dd/MM/yyyy");
                Nascimento.setTime(format.parse(TxNascimento.getText()));
                
                Calendar Validade = Calendar.getInstance();
                Validade.setTime(format.parse(TxValidade.getText()));
                
                Calendar DataAtual = new GregorianCalendar();
                
                if(TxNome.getText().equals("") && TxCPF.getText().equals("") && TxRegistro.getText().equals("")&& TxTelefone.getText().equals("")){
                    throw new Exception("EXISTEM CAMPOS OBRIGATÓRIOS A SERREM PREENCHIDOS");
                }else{
                    if(_detetive == null){
                        _detetive = new ODB_Detetive();
                        _detetive.setNome(TxNome.getText());
                        _detetive.setCPF(Criptografia.Cripto(TxCPF.getText()));
                        _detetive.setRG(Criptografia.Cripto(TxRG.getText()));
                        _detetive.setTitulo(Criptografia.Cripto(TxTitulo.getText()));
                        if(TxZona.getText().equals("")){
                            _detetive.setZona(0);
                        }else{
                            _detetive.setZona(Integer.parseInt(TxZona.getText()));}

                        if(TxSessao.getText().equals("")){
                            _detetive.setSessao(0);
                        }else{
                        _detetive.setSessao(Integer.parseInt(TxSessao.getText()));}

                        _detetive.setSexo(Selecionar.Consultar_IDSexo(CbSexo.getSelectedItem().toString()));
                        _detetive.setNascimento(Nascimento);
                        _detetive.setNaturalidade(TxNaturalidade.getText());
                        _detetive.setUF(CbUF.getSelectedItem().toString());
                        _detetive.setEstadoCivil(Selecionar.Consultar_IDEstadoCivil(CbEstadoCivil.getSelectedItem().toString()));
                        _detetive.setConjuge(TxConjuge.getName());
                        _detetive.setNomeMae(TxNomeMae.getText());
                        _detetive.setNomePai(TxNomePai.getText());
                        _detetive.setRegistroODB(Integer.parseInt(TxRegistro.getText()));
                        _detetive.setValidade(Validade);
                        _detetive.setTipoCadastro(Selecionar.Consultar_IDTipoCadastro(CbAssociado.getSelectedItem().toString()));
                        _detetive.setEmail(TxEmail.getText());
                        _detetive.setSite(TxSite.getText());
                        _detetive.setGrupo(Selecionar.Consultar_IDGrupo(CbGrupo.getSelectedItem().toString()));
                        _detetive.setAtivo(ChAtivo.isSelected());
                        _detetive.setAvisarAniversario(ChAniversario.isSelected());
                        _detetive.setDataCadastro(DataAtual);
                        _detetive.setFoto(ODB_Parameter.CaminhoFoto);
                        
                        Inserir.Criar_Detetives(_detetive);

                        Thread.sleep(50);
                        
                        _complemento = new ODB_DetetiveComplemento();

                        _complemento.setCodigoDetetive(Selecionar.Consultar_IDDetetive(Criptografia.Cripto(TxCPF.getText())));
                        _complemento.setCep(Integer.parseInt(TxCep.getText()));
                        _complemento.setEndereco(TxEndereco.getText());
                        _complemento.setComplemento(TxComplemento.getText());

                        if(TxNumero.getText().equals("")){
                            _complemento.setNumero(0);
                        }else{
                        _complemento.setNumero(Integer.parseInt(TxNumero.getText()));}
                        _complemento.setBairro(TxBairro.getText());
                        _complemento.setUFEndereco(TxUF.getText());
                        _complemento.setCidade(TxCidade.getText());
                        if(TxDDD.getText().equals("")){
                            _complemento.setDDD(0);
                        }else{
                        _complemento.setDDD(Integer.parseInt(TxDDD.getText()));}
                        _complemento.setTelefone(TxTelefone.getText());

                        Inserir.Criar_DetetivesComplemento(_complemento);
                
                    }else{//Atualiza Cadastro

                        _detetive.setNome(TxNome.getText());
                        _detetive.setCPF(Criptografia.Cripto(TxCPF.getText()));
                        _detetive.setRG(Criptografia.Cripto(TxRG.getText()));
                        _detetive.setTitulo(Criptografia.Cripto(TxTitulo.getText()));
                        if(TxZona.getText().equals("")){
                            _detetive.setZona(0);
                        }else{
                            _detetive.setZona(Integer.parseInt(TxZona.getText()));}

                        if(TxSessao.getText().equals("")){
                            _detetive.setSessao(0);
                        }else{
                        _detetive.setSessao(Integer.parseInt(TxSessao.getText()));}

                        _detetive.setSexo(Selecionar.Consultar_IDSexo(CbSexo.getSelectedItem().toString()));
                        _detetive.setNascimento(Nascimento);
                        _detetive.setNaturalidade(TxNaturalidade.getText());
                        _detetive.setUF(CbUF.getSelectedItem().toString());
                        _detetive.setEstadoCivil(Selecionar.Consultar_IDEstadoCivil(CbEstadoCivil.getSelectedItem().toString()));
                        _detetive.setConjuge(TxConjuge.getName());
                        _detetive.setNomeMae(TxNomeMae.getText());
                        _detetive.setNomePai(TxNomePai.getText());
                        _detetive.setRegistroODB(Integer.parseInt(TxRegistro.getText()));
                        _detetive.setValidade(Validade);
                        _detetive.setTipoCadastro(Selecionar.Consultar_IDTipoCadastro(CbAssociado.getSelectedItem().toString()));
                        _detetive.setEmail(TxEmail.getText());
                        _detetive.setSite(TxSite.getText());
                        _detetive.setGrupo(Selecionar.Consultar_IDGrupo(CbGrupo.getSelectedItem().toString()));
                        _detetive.setAtivo(ChAtivo.isSelected());
                        _detetive.setAvisarAniversario(ChAniversario.isSelected());
                        _detetive.setDataCadastro(DataAtual);
                        _detetive.setFoto(ODB_Parameter.CaminhoFoto);

                        _complemento.setCep(Integer.parseInt(TxCep.getText()));
                        _complemento.setEndereco(TxEndereco.getText());
                        _complemento.setComplemento(TxComplemento.getText());
                        _complemento.setNumero(Integer.parseInt(TxNumero.getText()));
                        _complemento.setBairro(TxBairro.getText());
                        _complemento.setUFEndereco(TxUF.getText());
                        _complemento.setCidade(TxCidade.getText());
                        _complemento.setDDD(Integer.parseInt(TxDDD.getText()));
                        _complemento.setTelefone(TxTelefone.getText());

                        }
                 }
                
        }catch(Exception  ex){
            _detetive = null;
            _complemento = null;
            
            JOptionPane.showMessageDialog(null,ex.getMessage(),"ERRO", JOptionPane.INFORMATION_MESSAGE, ODB_Parameter.icon);
        }
    }//GEN-LAST:event_BtSalvarActionPerformed

