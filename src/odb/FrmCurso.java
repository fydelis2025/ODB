    private void BtNovoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtNovoActionPerformed
        try{

            this._cursos = new ODB_Cursos();
            this._cursos.setID(Selecionar.Consultar_IDDetetive(Criptografia.Cripto(TxCPFCurso.getText())));
            this._cursos.setCPF(TxCPFCurso.getText());
            this._cursos.setCurso(TxCurso.getText());
            this._cursos.setCNPJ(TxCNPJ.getText());
            this._cursos.setInstituicao(TxInstituicao.getText());
            this._cursos.setConcluido(ChConcluido.isSelected());
            
            Inserir.Criar_DetetiveCursos(_cursos);
            
            this._cursos = null;

            TxCPFCurso.setText("");
            TxNomeCurso.setText("");
            TxCurso.setText("");
            TxCNPJ.setText("");
            TxInstituicao.setText("");

        }catch(Exception  ex){
            JOptionPane.showMessageDialog(null,"A DATA DEVE ESTA NO FORMATO (dd/MM/yyyy), FAVOR VERIFIQUE","ERRO", JOptionPane.INFORMATION_MESSAGE, ODB_Parameter.icon);
        }
    }//GEN-LAST:event_BtNovoActionPerformed

