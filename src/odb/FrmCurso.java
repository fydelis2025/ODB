    private void TxCPFCursoKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TxCPFCursoKeyPressed
        try{
            if(evt.getKeyCode() == KeyEvent.VK_ENTER){
                
                String Retorno = Selecionar.Consultar_CPFDetetive(Criptografia.Cripto(TxCPFCurso.getText()));
                
                if(Retorno.equals("")){
                    throw new Exception("DETETIVE NÃO ENCONTRADO, FAVOR VERIFIQUE");
                }else{
                    TxNomeCurso.setText(Retorno);
                    TxCurso.requestFocus();
                }
            }
        }catch(Exception ex){
            JOptionPane.showMessageDialog(null,ex.getMessage(),"ERRO", JOptionPane.INFORMATION_MESSAGE, ODB_Parameter.icon);
        }
    }//GEN-LAST:event_TxCPFCursoKeyPressed

    private void TxCPFCursoKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TxCPFCursoKeyTyped
        int ascii = evt.getKeyChar();
        
        if (!(ascii >= 48 && ascii <=57) && !(ascii == evt.VK_BACK_SPACE)){                        

                        evt.consume() ;

        }
    }//GEN-LAST:event_TxCPFCursoKeyTyped

