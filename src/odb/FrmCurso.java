    private void TxCNPJKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TxCNPJKeyPressed
        try{
            
            if(evt.getKeyCode() == KeyEvent.VK_ENTER){
                if(TxCNPJ.getText().equals("")){
                    throw new Exception("POR FAVOR INFORME UM CNPJ");
                }else{
                    ODB_Validador valida = new ODB_Validador();
                    Boolean Retorno = valida.isCNPJ(TxCNPJ.getText());

                    if(Retorno.equals(true)){
                        TxInstituicao.requestFocus();
                    }else{
                        throw new Exception("CNPJ INVALIDO, FAVOR VERIFIQUE");
                    }
                }
            }

        }catch(Exception ex){
            JOptionPane.showMessageDialog(null,ex.getMessage(),"ERRO", JOptionPane.INFORMATION_MESSAGE, ODB_Parameter.icon);
        }
    }//GEN-LAST:event_TxCNPJKeyPressed

